def _merge(*snapshots: Dict[str, FrozenSet[str]]) -> Dict[str, FrozenSet[str]]:
    merged: Dict[str, FrozenSet[str]] = {}
    for snapshot in snapshots:
        for toolset, tools in snapshot.items():
            merged[toolset] = merged.get(toolset, frozenset()) | tools
    return merged


