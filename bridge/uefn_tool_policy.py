"""Pinned UEFN creator tool policy for safe in-process registry calls.

The Toolset Registry contains toolsets that UEFN intentionally does not expose
to creators. This module is a fail-closed snapshot of the toolsets and tools
described by the official UEFN MCP server for each recorded UEFN build. A tool
runs locally only when it is in a snapshot here AND the running editor's
registry exposes it, so the 42.40 names never run on 43.00 or the reverse.

42.40 (CL 59247843) re-pin, from the MCP server's tools/list with Python on:
VerseFieldsToolset gained GetSupportedVerseFieldTypes; SceneTools gained
is_actor_hidden, set_actor_hidden, replace_actors_with_asset and
replace_actors_with_class and lost the three *_level_instance tools. The new
editor_toolset.toolsets.programmatic.ProgrammaticToolset (execute_tool_script,
get_execution_environment) is deliberately left out: it runs arbitrary tool
scripts, which the bridge's own exec command already covers under its rules.

43.00 (CL 59596594) pin, from list_toolsets plus describe_toolset for all 56
toolsets on rocky, 2026-11-02 (the local registry listed the same 56 with the
same tools). Epic renamed most toolsets: ValkyrieToolset.VerseToolset became
VerseToolset.VerseToolset; the Session and Device toolsets moved to
ValkyrieFortniteToolset; EditorToolset.LogsToolset became
ConsoleToolset.LogsToolset; editor_toolset.toolsets.* became EditorToolset.*
with PascalCase tool names (SceneTools is now LevelToolset);
ValkyriePythonToolset's tools became IsPythonReadyForMainProject and
EnablePythonForMainProject. ProgrammaticToolset and the new
editor_toolset.toolsets.python_scripting.PythonScriptingTools stay out for the
same reason as above.
"""

